    /*
    |--------------------------------------------------------------------------
    | Application Environment
    |--------------------------------------------------------------------------
    |
    | This value determines the "environment" your application is currently
    | running in. This may determine how you prefer to configure various
    | services the application utilizes. Set this in your ".env" file.
    |
    */

    'env' => env('APP_ENV', 'production'),

    /*
    |--------------------------------------------------------------------------
    | Application Debug Mode
    |--------------------------------------------------------------------------
    |
    | When your application is in debug mode, detailed error messages with
    | stack traces will be shown on every error that occurs within your
    | application. If disabled, a simple generic error page is shown.
    |
    */

    'debug' => (bool) env('APP_DEBUG', false),

    /*
    |--------------------------------------------------------------------------
    | Application URL
    |--------------------------------------------------------------------------
    |
    | This URL is used by the console to properly generate URLs when using
    | the Artisan command line tool. You should set this to the root of
    | the application so that it's available within Artisan commands.
    |
    */

    'url' => env('APP_URL', 'http://localhost'),

    /*
    |--------------------------------------------------------------------------
    | Application Timezone
    |--------------------------------------------------------------------------
    |
    | Here you may specify the default timezone for your application, which
    | will be used by the PHP date and date-time functions. The timezone
    | is set to "UTC" by default as it is suitable for most use cases.
    |
    */

    // Riyadh, not UTC. Every timestamp Laravel writes and reads is now in the
    // zone the business runs in, so now(), the scheduler, the logs and the
    // admin all agree with the clock on the wall.
    //
    // This only holds because the database connection is pinned to +03:00 as
    // well: MySQL keeps TIMESTAMP columns in UTC internally and converts them
    // on the way in and out, so both ends must name the same zone or every
    // read is three hours off what was written.
    'timezone' => env('APP_TIMEZONE', 'Asia/Riyadh'),

    /*
    |--------------------------------------------------------------------------
    | Business Timezone
    |--------------------------------------------------------------------------
    |
    | Velto operates in one country, and a booking time is a wall-clock time in
    | it: a customer choosing 21:00 means 21:00 in Riyadh. Those values are
    | stored naively, built from the time slot's date and start_time, so they
    | must be serialised with this offset rather than the app timezone above.
    | Emitting them as UTC made every client shift a booking by three hours.
    |
    | Event timestamps — accepted_at, completed_at — are real instants recorded
    | with now() and stay UTC.
    |
    */

    'business_timezone' => env('APP_BUSINESS_TIMEZONE', 'Asia/Riyadh'),

    /*
    |--------------------------------------------------------------------------
    | Application Locale Configuration
    |--------------------------------------------------------------------------
    |
    | The application locale determines the default locale that will be used
    | by Laravel's translation / localization methods. This option can be
    | set to any locale for which you plan to have translation strings.
    |
    */

    'locale' => env('APP_LOCALE', 'en'),

    'fallback_locale' => env('APP_FALLBACK_LOCALE', 'en'),

    'faker_locale' => env('APP_FAKER_LOCALE', 'en_US'),

    /*
    |--------------------------------------------------------------------------
    | Encryption Key
